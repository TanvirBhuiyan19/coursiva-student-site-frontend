/** Next Thursday, 2pm US Pacific (21:00 UTC during daylight time). */
function nextThursdayAt14() {
  const d = new Date(now);
  d.setUTCDate(d.getUTCDate() + ((4 - d.getUTCDay() + 7) % 7 || 7));
  d.setUTCHours(21, 0, 0, 0);
  return d.toISOString();
}

